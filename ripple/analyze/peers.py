def peers_of(industry: str | None, self_code: str | None = None,
             limit: int = 4) -> list[str]:
    """按行业返回同行代表股，把自身放最前面。命中不到就返回空列表。"""
    if not industry:
        return []
    peers = list(INDUSTRY_PEERS.get(industry, []))
    if not peers:
        return []
    if self_code and self_code in peers:
        peers.remove(self_code)
        peers.insert(0, self_code)
    elif self_code:
        # 自己不在预设里，也放进去
        peers.insert(0, self_code)
    return peers[:limit]
